"""
make_submission_figure.py -- Figure 3 of the JCE revision.

Panel (a): mean verification time with one sample standard deviation for
the explicit-key and recovered-key (compact) encodings, from
results_submission.json (generated by experiment_submission.py).

Panel (b): authentication-path construction cost.  For each (w,h)
configuration the same 45 sampled leaves are timed twice:
   * rebuilt: recompute the path by rebuilding the tree from the leaf
     layer (2^h - 1 internal hashes per path);
   * cached:  look up siblings from a cached full tree (h reads, no new
     tree hashes).
The per-base median is reported; panel (b) averages the three per-base
path-time medians at each height, as stated in the paper.

Outputs figure3.png, figure3.svg, and path_traversal.json.
"""
from __future__ import annotations

import json
import math
import random
import statistics
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import sys as _sys
_sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "experiments"))

from experiment_submission import (
    CONFIGS, TREES_PER_CONFIG, MEASURED_LEAVES, N,
    H, leaf_seed, wots_key, leaf_hash, node_hash, build_tree,
    W_TO_CODE, params,
)

OUT = Path(__file__).resolve().parents[1]


def path_timings(w: int, h: int, rng: random.Random):
    """Rebuild vs cached path timings for the 45 sampled leaves of (w,h)."""
    rebuilt, cached = [], []
    for t in range(TREES_PER_CONFIG):
        tree_seed = H(b"SUB-TREE" + bytes([W_TO_CODE[w], h, t]))
        leaves_pk, layers = build_tree(tree_seed, w, h)
        if h == 4:
            indices = list(range(1, 1 + MEASURED_LEAVES))
        else:
            indices = [1 + 17 * j for j in range(MEASURED_LEAVES)]
        for leaf in indices:
            # rebuilt: hash all internal nodes from the leaf layer
            t0 = time.perf_counter_ns()
            layer = layers[0]
            while len(layer) > 1:
                if len(layer) % 2 == 1:
                    layer = layer + [layer[-1]]
                layer = [node_hash(layer[2 * i], layer[2 * i + 1])
                         for i in range(len(layer) // 2)]
            t1 = time.perf_counter_ns()
            rebuilt.append((t1 - t0) / 1e6)
            # cached: read the h siblings from the stored layers
            t0 = time.perf_counter_ns()
            cur = leaf
            for lvl in range(h):
                layer = layers[lvl]
                if len(layer) % 2 == 1:
                    layer = layer + [layer[-1]]
                _ = layer[cur ^ 1]
                cur //= 2
            t1 = time.perf_counter_ns()
            cached.append((t1 - t0) / 1e6)
    return rebuilt, cached


def main():
    if not (OUT / "experiments" / "results_submission.json").exists():
        raise SystemExit("results_submission.json missing; run "
                         "experiment_submission.py first")
    results = json.loads((OUT / "experiments" / "results_submission.json").read_text())
    rng = random.Random(20260915)

    # --- panel (a) data ---
    labels = []
    exp_mean, exp_sd, com_mean, com_sd = [], [], [], []
    for w, h in CONFIGS:
        key = f"w={w},h={h}"
        c = results["configs"][key]
        labels.append(f"w={w}\nh={h}")
        exp_mean.append(c["explicit_verify_ms"]["mean"])
        exp_sd.append(c["explicit_verify_ms"]["sd"])
        com_mean.append(c["compact_verify_ms"]["mean"])
        com_sd.append(c["compact_verify_ms"]["sd"])

    # --- panel (b) data ---
    trav = {}
    h_rebuilt_avg, h_cached_avg = [], []
    for w, h in CONFIGS:
        rebuilt, cached = path_timings(w, h, rng)
        trav[f"w={w},h={h}"] = {
            "rebuilt_median_ms": statistics.median(rebuilt),
            "cached_median_ms": statistics.median(cached),
            "rebuilt_n": len(rebuilt),
            "cached_n": len(cached),
        }
    for h in (4, 8):
        meds = [trav[f"w={w},h={h}"]["rebuilt_median_ms"]
                for w in (4, 16, 256)]
        cmeds = [trav[f"w={w},h={h}"]["cached_median_ms"]
                 for w in (4, 16, 256)]
        h_rebuilt_avg.append(statistics.mean(meds))
        h_cached_avg.append(statistics.mean(cmeds))

    # --- figure ---
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.2))
    x = range(len(labels))
    wdt = 0.36
    ax1.bar([i - wdt / 2 for i in x], exp_mean, wdt, yerr=exp_sd,
            label="Explicit (endpoints transmitted)", capsize=3,
            color="#c0392b", alpha=0.85, error_kw={"lw": 1})
    ax1.bar([i + wdt / 2 for i in x], com_mean, wdt, yerr=com_sd,
            label="Compact (endpoints recovered)", capsize=3,
            color="#2980b9", alpha=0.85, error_kw={"lw": 1})
    ax1.set_xticks(list(x))
    ax1.set_xticklabels(labels, fontsize=9)
    ax1.set_ylabel("Mean verification time (ms)")
    ax1.set_title("(a) Paired verification, 45 observations per bar")
    ax1.legend(fontsize=8)
    ax1.grid(axis="y", alpha=0.3)

    ax2.bar([0, 1], h_rebuilt_avg, wdt, label="Rebuilt from leaf layer",
            color="#c0392b", alpha=0.85)
    ax2.bar([0.5 + 1, 1.5 + 1], h_cached_avg, wdt,
            label="Cached full tree", color="#2980b9", alpha=0.85)
    ax2.set_xticks([0, 1, 2, 3])
    ax2.set_xticklabels(["h=4", "h=8", "h=4", "h=8"], fontsize=9)
    ax2.set_ylabel("Path time, mean of per-base medians (ms)")
    ax2.set_title("(b) Authentication path construction")
    ax2.legend(fontsize=8)
    ax2.grid(axis="y", alpha=0.3)

    fig.tight_layout()
    fig.savefig(OUT / "figures" / "figure3.png", dpi=160)
    fig.savefig(OUT / "figures" / "figure3.svg")
    print("[written] figure3.png / figure3.svg")

    trav_out = {
        "per_config": trav,
        "height_means": {"h=4": {"rebuilt": h_rebuilt_avg[0],
                                 "cached": h_cached_avg[0]},
                         "h=8": {"rebuilt": h_rebuilt_avg[1],
                                 "cached": h_cached_avg[1]}},
        "note": "Per-base medians over 45 observations; height means average the three per-base medians.",
    }
    (OUT / "figures" / "path_traversal.json").write_text(json.dumps(trav_out, indent=2))
    print("[written] path_traversal.json")
    for k, v in trav.items():
        print(k, "rebuilt", round(v["rebuilt_median_ms"], 4),
              "cached", round(v["cached_median_ms"], 4))


if __name__ == "__main__":
    main()
