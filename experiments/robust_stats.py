"""robust_stats.py -- Robust descriptive statistics for Section 6.4 (Table 8b)
of the JCE revision, computed from the retained raw samples in
results_submission.json.

For each (w, h) configuration this script reports, for the explicit-key and
recovered-key verification timings: median, first/third quartile, interquartile
range, minimum, and maximum, alongside the mean and sample standard deviation of
Table 8.  It also reports the per-event paired difference
(explicit_ms - compact_ms) with median and IQR, plus the share of events in
which the explicit mode was slower, and a tree-level grouping: for each of the
three independent trees, the median over its 15 leaves, so that tree-level
spread is visible without assuming within-tree observations are independent
repetitions.

No sample is removed: min/max columns expose the long tail that inflates the
sample standard deviation.

Run:  python3 experiments/robust_stats.py
Writes: experiments/robust_stats.json
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

OUT = Path(__file__).resolve().parents[1]
SRC = OUT / "experiments" / "results_submission.json"
DST = OUT / "experiments" / "robust_stats.json"

CONFIG_ORDER = ["w=4,h=4", "w=4,h=8", "w=16,h=4", "w=16,h=8", "w=256,h=4", "w=256,h=8"]


def q1_q3(vals):
    s = sorted(vals)
    n = len(s)
    q1 = s[n // 4] if n % 4 else (s[n // 4 - 1] + s[n // 4]) / 2
    q3 = s[3 * n // 4] if n % 4 else (s[3 * n // 4 - 1] + s[3 * n // 4]) / 2
    return q1, q3


def stats(vals):
    q1, q3 = q1_q3(vals)
    return {
        "n": len(vals),
        "mean_ms": statistics.mean(vals),
        "sd_ms": statistics.stdev(vals) if len(vals) > 1 else 0.0,
        "median_ms": statistics.median(vals),
        "q1_ms": q1,
        "q3_ms": q3,
        "iqr_ms": q3 - q1,
        "min_ms": min(vals),
        "max_ms": max(vals),
    }


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    raw = d["raw_samples"]
    per_config = {}
    for i, cfg in enumerate(CONFIG_ORDER):
        blk = raw[i * 45:(i + 1) * 45]
        exp = [r["explicit_verify_ms"] for r in blk]
        com = [r["compact_verify_ms"] for r in blk]
        diff = [e - c for e, c in zip(exp, com)]
        # tree-level grouping: each of the 3 trees is a primary unit
        tree_level = {}
        for t in sorted({r["tree"] for r in blk}):
            e_t = [r["explicit_verify_ms"] for r in blk if r["tree"] == t]
            c_t = [r["compact_verify_ms"] for r in blk if r["tree"] == t]
            tree_level[t] = {
                "leaves": len(e_t),
                "explicit_median_ms": statistics.median(e_t),
                "compact_median_ms": statistics.median(c_t),
            }
        per_config[cfg] = {
            "explicit": stats(exp),
            "compact": stats(com),
            "tree_level": tree_level,
            "paired_diff_explicit_minus_compact": {
                "median_ms": statistics.median(diff),
                "q1_ms": q1_q3(diff)[0],
                "q3_ms": q1_q3(diff)[1],
                "iqr_ms": q1_q3(diff)[1] - q1_q3(diff)[0],
                "mean_ms": statistics.mean(diff),
                "explicit_slower_share": sum(1 for x in diff if x > 0) / len(diff),
            },
        }

    out = {
        "per_config": per_config,
        "note": (
            "Generated by experiments/robust_stats.py from results_submission.json. "
            "All raw samples retained; no outlier removed. Median/IQR complement "
            "the mean +/- SD of Table 8 because a minority of long-tailed samples "
            "inflates the sample standard deviation (see min/max). Tree-level "
            "medians treat each of the three independent trees as a grouping unit; "
            "within-tree observations share a root and path structure."),
    }
    DST.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    for cfg, v in per_config.items():
        e, c = v["explicit"], v["compact"]
        p = v["paired_diff_explicit_minus_compact"]
        print(f"{cfg}: explicit med {e['median_ms']:.4f} IQR {e['iqr_ms']:.4f} "
              f"max {e['max_ms']:.3f} | compact med {c['median_ms']:.4f} "
              f"IQR {c['iqr_ms']:.4f} max {c['max_ms']:.3f} | diff med {p['median_ms']:+.4f} "
              f"explicit_slower {p['explicit_slower_share']:.0%}")
    print("[written]", DST)


if __name__ == "__main__":
    main()
